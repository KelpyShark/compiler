        self.line(r#"function ksLen(v) { if (typeof v==='string') return Array.from(v).length; if (Array.isArray(v)) return v.length; if (ksIsDict(v)) return Object.keys(v).length; throw new TypeError('len() is not supported for '+ksType(v)); }"#);
