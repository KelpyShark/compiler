/// KelpyShark → C# Code Generator
///
/// Transpiles a KelpyShark AST into C# source code.
///
/// Strategy:
///   - All KelpyShark values are represented as `object` (C#'s universal base type).
///   - The `dynamic` keyword is used for arithmetic/comparisons to avoid casts.
///   - A static runtime helpers region is emitted at the top of the class.
///   - User-defined functions become private static methods on `Program`.
///   - The top-level program runs in `Main(string[] args)`.
///   - KelpyShark classes become nested static classes.

use crate::ast::*;
use std::collections::HashSet;

/// Generate C# source after validating that the target supports the program.
pub fn generate(program: &Program) -> Result<String, String> {
    generate_checked(program)
}

/// Generate C# without target validation. Prefer [`generate`] for user input.
fn generate_unchecked(program: &Program) -> String {
    let functions = program.statements.iter().filter_map(|statement| match statement {
        Statement::FunctionDef { name, .. } => Some(name.clone()),
        _ => None,
    }).collect();
    let mut gen = CsGenerator::new(functions);
    gen.emit_program(program);
    gen.output
}

/// Generate C# only when the program uses constructs supported by this backend.
pub fn generate_checked(program: &Program) -> Result<String, String> {
    super::validation::validate_managed_target(program, "C#")?;
    Ok(generate_unchecked(program))
}

struct CsGenerator {
    output: String,
    indent: usize,
    variable_aliases: Vec<(String, String)>,
    temp_counter: usize,
    user_functions: HashSet<String>,
    global_variables: HashSet<String>,
}

impl CsGenerator {
    fn new(user_functions: HashSet<String>) -> Self {
        CsGenerator {
            output: String::new(),
            indent: 0,
            variable_aliases: Vec::new(),
            temp_counter: 0,
            user_functions,
            global_variables: HashSet::new(),
        }
    }

    fn line(&mut self, text: &str) {
        let indent_str = "    ".repeat(self.indent);
        self.output.push_str(&format!("{}{}\n", indent_str, text));
    }

    fn blank(&mut self) {
        self.output.push('\n');
    }

    fn variable(&self, name: &str) -> String {
        self.variable_aliases
            .iter()
            .rev()
            .find(|(source, _)| source == name)
            .map(|(_, target)| target.clone())
            .unwrap_or_else(|| variable_name(name))
    }

    fn unique_temp(&mut self, prefix: &str) -> String {
        let name = format!("{}_{}", prefix, self.temp_counter);
        self.temp_counter += 1;
        name
    }

    // ── Program ──────────────────────────────────────────────

    fn emit_program(&mut self, program: &Program) {
        self.global_variables = collect_global_variables(&program.statements);
        self.line("#nullable disable");
        self.line("// Generated by KelpyShark Compiler v0.2.0");
        self.line("using System.Collections;");
        self.line("using System;");
        self.line("using System.Collections.Generic;");
        self.line("using System.Globalization;");
        self.line("using System.Linq;");
        self.line("using System.Text;");
        self.blank();
        self.line("class Program {");
        self.indent += 1;

        self.emit_runtime_helpers();
        self.blank();

        let mut globals: Vec<_> = self.global_variables.iter().cloned().collect();
        globals.sort();
        for name in globals { self.line(&format!("static object {} = null;", variable_name(&name))); }
        if !self.global_variables.is_empty() { self.blank(); }

        // Inner class definitions
        for stmt in &program.statements {
            if let Statement::ClassDef { .. } = stmt {
                self.emit_statement(stmt);
                self.blank();
            }
        }

        // User-defined functions
        for stmt in &program.statements {
            if let Statement::FunctionDef { .. } = stmt {
                self.emit_statement(stmt);
                self.blank();
            }
        }

        // Entry point
        self.line("static void Main(string[] args) {");
        self.indent += 1;
        let globals = self.global_variables.clone();
        emit_variable_declarations(self, &program.statements, &HashSet::new(), &globals);
        for stmt in &program.statements {
            match stmt {
                Statement::FunctionDef { .. } | Statement::ClassDef { .. } => continue,
                _ => self.emit_statement(stmt),
            }
        }
        self.indent -= 1;
        self.line("}");

        self.indent -= 1;
        self.line("}");
    }

    // ── Runtime helpers ───────────────────────────────────────

    fn emit_runtime_helpers(&mut self) {
        // Print
        self.line("#region Runtime");
        self.line("static object KsPrint(object v) {");
        self.indent += 1;
        self.line("Console.WriteLine(KsStr(v));");
        self.line("return null;");
        self.indent -= 1;
        self.line("}");
        self.blank();

        // Truthiness
        self.line("static bool KsTruthy(object v) {");
        self.indent += 1;
        self.line("if (v == null) return false;");
        self.line("if (v is bool b) return b;");
        self.line("if (v is double d) return d != 0.0;");
        self.line("if (v is string s) return s.Length > 0;");
        self.line("if (v is List<object> l) return l.Count > 0;");
        self.line("if (v is Dictionary<object,object> dict) return dict.Count > 0;");
        self.line("return true;");
        self.indent -= 1;
        self.line("}");
        self.blank();

        // Add / concat
        self.line("static object KsAdd(object a, object b) {");
        self.indent += 1;
        self.line("if (a is double da && b is double db) return da + db;");
        self.line("return KsStr(a) + KsStr(b);");
        self.indent -= 1;
        self.line("}");
        self.blank();

        // Arithmetic
        self.line("static object KsSub(object a, object b) => (double)a - (double)b;");
        self.line("static object KsMul(object a, object b) => (double)a * (double)b;");
        self.line("static object KsDiv(object a, object b) => (double)a / (double)b;");
        self.line("static object KsMod(object a, object b) => (double)a % (double)b;");
        self.blank();

        // Comparison
        self.line("static object KsEq(object a, object b) {");
        self.indent += 1;
        self.line("return KsEqInner(a, b, new HashSet<Tuple<object,object>>());");
        self.indent -= 1;
        self.line("}");
        self.line("static bool KsEqInner(object a, object b, HashSet<Tuple<object,object>> seen) {");
        self.indent += 1;
        self.line("if (a == null && b == null) return true;");
        self.line("if (a == null || b == null) return false;");
        self.line("if (a is double da && b is double db) return da == db;");
        self.line("if (a is IList al && b is IList bl) { if (!seen.Add(Tuple.Create(a, b))) return true; if (al.Count != bl.Count) return false; for (int i = 0; i < al.Count; i++) if (!KsEqInner(al[i], bl[i], seen)) return false; return true; }");
        self.line("if (a is IDictionary ad && b is IDictionary bd) { if (!seen.Add(Tuple.Create(a, b))) return true; if (ad.Count != bd.Count) return false; foreach (DictionaryEntry entry in ad) if (!bd.Contains(entry.Key) || !KsEqInner(entry.Value, bd[entry.Key], seen)) return false; return true; }");
        self.line("return a.Equals(b);");
        self.indent -= 1;
        self.line("}");
        self.line("static object KsNeq(object a, object b) => !(bool)KsEq(a, b);");
        self.line("static object KsLt(object a, object b)  => (double)a < (double)b;");
        self.line("static object KsLe(object a, object b)  => (double)a <= (double)b;");
        self.line("static object KsGt(object a, object b)  => (double)a > (double)b;");
        self.line("static object KsGe(object a, object b)  => (double)a >= (double)b;");
        self.blank();

        // Type helpers
        self.line("static string KsStr(object v) {");
        self.indent += 1;
        self.line("return KsFormat(v, false, new HashSet<object>());");
        self.indent -= 1;
        self.line("}");
        self.line("static string KsFormat(object v, bool nested, HashSet<object> active) {");
        self.indent += 1;
        self.line("if (v == null) return \"null\";");
        self.line("if (v is double d) return d == Math.Floor(d) && d >= long.MinValue && d < long.MaxValue ? ((long)d).ToString(CultureInfo.InvariantCulture) : d.ToString(CultureInfo.InvariantCulture);");
        self.line("if (v is bool b) return b ? \"true\" : \"false\";");
        self.line("if (v is string text) return nested ? KsQuote(text) : text;");
        self.line("if (v is List<object> list) { if (!active.Add(v)) return \"[<cycle>]\"; var parts = list.Select(item => KsFormat(item, true, active)).ToList(); active.Remove(v); return \"[\" + string.Join(\", \", parts) + \"]\"; }");
        self.line("if (v is Dictionary<object,object> dict) { if (!active.Add(v)) return \"{<cycle>}\"; var keys = dict.Keys.Select(KsStr).OrderBy(key => key, StringComparer.Ordinal); var parts = keys.Select(key => KsQuote(key) + \": \" + KsFormat(dict[key], true, active)).ToList(); active.Remove(v); return \"{\" + string.Join(\", \", parts) + \"}\"; }");
        self.line("return v.ToString();");
        self.indent -= 1;
        self.line("}");
        self.line("static string KsQuote(string value) => \"\\\"\" + value.Replace(\"\\\\\", \"\\\\\\\\\").Replace(\"\\\"\", \"\\\\\\\"\").Replace(\"\\n\", \"\\\\n\").Replace(\"\\r\", \"\\\\r\").Replace(\"\\t\", \"\\\\t\") + \"\\\"\";");
        self.blank();

        self.line("static object KsType(object v) {");
        self.indent += 1;
        self.line("if (v == null) return \"null\";");
        self.line("if (v is double) return \"number\";");
        self.line("if (v is string) return \"string\";");
        self.line("if (v is bool) return \"boolean\";");
        self.line("if (v is List<object>) return \"list\";");
        self.line("if (v is Dictionary<object,object>) return \"dict\";");
        self.line("return \"object\";");
        self.indent -= 1;
        self.line("}");
        self.blank();

        // len()
        self.line("static object KsLen(object v) {");
        self.indent += 1;
        self.line("if (v is string s) return (double)s.EnumerateRunes().Count();");
        self.line("if (v is List<object> l) return (double)l.Count;");
        self.line("if (v is Dictionary<object,object> d) return (double)d.Count;");
        self.line("throw new Exception(\"len() not supported for \" + KsType(v));");
        self.indent -= 1;
        self.line("}");
        self.blank();

        // push()
        self.line("static object KsPush(object list, object val) {");
        self.indent += 1;
        self.line("((List<object>)list).Add(val);");
        self.line("return list;");
        self.indent -= 1;
        self.line("}");
        self.blank();

        self.line("static string KsKey(object key) => KsStr(key);");
        self.line("static object KsDict(params object[] pairs) {");
        self.indent += 1;
        self.line("if (pairs.Length % 2 != 0) throw new Exception(\"Invalid dictionary literal\");");
        self.line("var result = new Dictionary<object,object>();");
        self.line("for (int i = 0; i < pairs.Length; i += 2) result[KsKey(pairs[i])] = pairs[i + 1];");
        self.line("return result;");
        self.indent -= 1;
        self.line("}");
        self.line("static object KsMember(object obj, string name) {");
        self.indent += 1;
        self.line("if (!(obj is Dictionary<object,object> map)) throw new Exception(\"Cannot access member on non-dictionary\");");
        self.line("if (!map.ContainsKey(name)) throw new Exception(\"Key not found in dict: \" + name);");
        self.line("return map[name];");
        self.indent -= 1;
        self.line("}");
        self.line("static int KsIndexValue(object index, int length) {");
        self.indent += 1;
        self.line("if (!(index is double value) || double.IsNaN(value) || double.IsInfinity(value) || value != Math.Floor(value)) throw new Exception(\"Index must be a whole number\");");
        self.line("double normalized = value < 0 ? length + value : value;");
        self.line("if (normalized < 0 || normalized >= length || normalized > int.MaxValue) throw new Exception(\"Index out of bounds (length \" + length + \")\");");
        self.line("return (int)normalized;");
        self.indent -= 1;
        self.line("}");
        self.line("static List<object> KsStringChars(string value) => value.EnumerateRunes().Select(r => (object)r.ToString()).ToList();");
        self.line("static IEnumerable<object> KsIter(object value) {");
        self.indent += 1;
        self.line("if (value is List<object> list) return list.ToList();");
        self.line("if (value is Dictionary<object,object> dict) return dict.Keys.OrderBy(KsStr, StringComparer.Ordinal).Cast<object>().ToList();");
        self.line("if (value is string text) return KsStringChars(text);");
        self.line("throw new Exception(\"Value is not iterable\");");
        self.indent -= 1;
        self.line("}");
        self.blank();

        // Index access
        self.line("static object KsIndex(object obj, object idx) {");
        self.indent += 1;
        self.line("if (obj is List<object> l) return l[KsIndexValue(idx, l.Count)];");
        self.line("if (obj is Dictionary<object,object> d) return d[KsKey(idx)];");
        self.line("if (obj is string s) { var chars = KsStringChars(s); return chars[KsIndexValue(idx, chars.Count)]; }");
        self.line("throw new Exception(\"Cannot index \" + KsType(obj));");
        self.indent -= 1;
        self.line("}");
        self.blank();
        self.line("static void KsSetIndex(object obj, object idx, object value) {");
        self.indent += 1;
        self.line("if (obj is List<object> l) { l[KsIndexValue(idx, l.Count)] = value; return; }");
        self.line("if (obj is Dictionary<object,object> d) { d[KsKey(idx)] = value; return; }");
        self.line("throw new Exception(\"Cannot assign index on \" + KsType(obj));");
        self.indent -= 1;
        self.line("}");
        self.line("static object KsNum(object value) => KsNumber(value, \"number\");");
        self.line("static object KsFloat(object value) => KsNum(value);");
        self.line("static object KsInt(object value) => (double)(long)(double)KsNumber(value, \"int\");");
        self.line("static double KsNumber(object value, string name) {");
        self.indent += 1;
        self.line("if (value is double d) return d;");
        self.line("if (value is bool b) return b ? 1.0 : 0.0;");
        self.line("if (value is string s && double.TryParse(s, NumberStyles.Float, CultureInfo.InvariantCulture, out double parsed)) return parsed;");
        self.line("throw new Exception(\"Cannot convert value to \" + name);");
        self.indent -= 1;
        self.line("}");
        self.line("static object KsAbs(object value) => Math.Abs((double)value);");
        self.line("static object KsSqrt(object value) => Math.Sqrt((double)value);");
        self.line("static object KsFloor(object value) => Math.Floor((double)value);");
        self.line("static object KsCeil(object value) => Math.Ceiling((double)value);");
        self.line("static object KsRound(object value) { double d = (double)value; return d < 0 ? -Math.Floor(Math.Abs(d) + 0.5) : Math.Floor(Math.Abs(d) + 0.5); }");
        self.line("static object KsMin(object a, object b) => Math.Min((double)a, (double)b);");
        self.line("static object KsMax(object a, object b) => Math.Max((double)a, (double)b);");
        self.line("static object KsPow(object a, object b) => Math.Pow((double)a, (double)b);");
        self.line("static object KsInput(object prompt) { Console.Write(KsStr(prompt)); return Console.ReadLine(); }");
        self.line("static List<object> KsRange(params object[] args) {");
        self.indent += 1;
        self.line("if (args.Length < 1 || args.Length > 3) throw new Exception(\"range() expects 1 to 3 arguments\");");
        self.line("double start = args.Length == 1 ? 0.0 : (double)args[0];");
        self.line("double stop = (double)args[args.Length == 1 ? 0 : 1];");
        self.line("double step = args.Length == 3 ? (double)args[2] : 1.0;");
        self.line("if (double.IsNaN(start) || double.IsInfinity(start) || double.IsNaN(stop) || double.IsInfinity(stop) || double.IsNaN(step) || double.IsInfinity(step) || step == 0.0) throw new Exception(\"range() requires finite numbers and a non-zero step\");");
        self.line("double count = ((step > 0 && start < stop) || (step < 0 && start > stop)) ? Math.Ceiling(Math.Abs((stop - start) / step)) : 0.0;");
        self.line("if (double.IsNaN(count) || double.IsInfinity(count) || count > 1000000) throw new Exception(\"range() exceeds the 1000000 item limit\");");
        self.line("var result = new List<object>(); double current = start;");
        self.line("while ((step > 0 && current < stop) || (step < 0 && current > stop)) { result.Add(current); double next = current + step; if (next == current) throw new Exception(\"range() step is too small to advance at this magnitude\"); current = next; }");
        self.line("return result;");
        self.indent -= 1;
        self.line("}");
        self.line("#endregion");
    }

    // ── Statements ────────────────────────────────────────────

    fn emit_statement(&mut self, stmt: &Statement) {
        match stmt {
            Statement::Assignment { name, value, .. } => {
                let v = self.emit_expr(value);
                self.line(&format!("{} = {};", self.variable(name), v));
            }
            Statement::MemberAssignment { object, member, value, .. } => {
                self.line(&format!("((Dictionary<object,object>)({}))[\"{}\"] = {};", self.emit_expr(object), member, self.emit_expr(value)));
            }
            Statement::IndexAssignment { object, index, value, .. } => {
                self.line(&format!("KsSetIndex({}, {}, {});", self.emit_expr(object), self.emit_expr(index), self.emit_expr(value)));
            }
            Statement::CompoundAssignment { name, op, value, .. } => {
                let v = self.emit_expr(value);
                let helper = match op {
                    CompoundOp::Add      => "KsAdd",
                    CompoundOp::Subtract => "KsSub",
                    CompoundOp::Multiply => "KsMul",
                    CompoundOp::Divide   => "KsDiv",
                };
                let variable = self.variable(name);
                self.line(&format!("{} = {}({}, {});", variable, helper, variable, v));
            }
            Statement::FunctionDef { name, params, body, .. } => {
                let param_list = params
                    .iter()
                    .map(|p| format!("object {}", self.variable(p)))
                    .collect::<Vec<_>>()
                    .join(", ");
                self.line(&format!("static object Ks_{}({}) {{", name, param_list));
                self.indent += 1;
                let parameters = params.iter().cloned().collect();
                let globals = self.global_variables.clone();
                emit_variable_declarations(self, body, &parameters, &globals);
                for s in body {
                    self.emit_statement(s);
                }
                if !sequence_terminates(body) {
                    self.line("return null;");
                }
                self.indent -= 1;
                self.line("}");
            }
            Statement::If { condition, then_body, else_body, .. } => {
                let cond = self.emit_expr(condition);
                self.line(&format!("if (KsTruthy({})) {{", cond));
                self.indent += 1;
                for s in then_body {
                    self.emit_statement(s);
                }
                self.indent -= 1;
                if let Some(else_stmts) = else_body {
                    self.line("} else {");
                    self.indent += 1;
                    for s in else_stmts {
                        self.emit_statement(s);
                    }
                    self.indent -= 1;
                }
                self.line("}");
            }
            Statement::While { condition, body, .. } => {
                let cond = self.emit_expr(condition);
                self.line(&format!("while (KsTruthy({})) {{", cond));
                self.indent += 1;
                for s in body {
                    self.emit_statement(s);
                }
                self.indent -= 1;
                self.line("}");
            }
            Statement::For { variable, iterable, body, .. } => {
                let iter = self.emit_expr(iterable);
                let loop_item = self.unique_temp("ksIterItem");
                self.line(&format!("foreach (object {} in KsIter({})) {{", loop_item, iter));
                self.indent += 1;
                self.line(&format!("{} = {};", self.variable(variable), loop_item));
                for s in body {
                    self.emit_statement(s);
                }
                self.indent -= 1;
                self.line("}");
            }
            Statement::Return { value, .. } => {
                let val = match value {
                    Some(expr) => self.emit_expr(expr),
                    None => "null".to_string(),
                };
                self.line(&format!("return {};", val));
            }
            Statement::Break { .. }    => self.line("break;"),
            Statement::Continue { .. } => self.line("continue;"),
            Statement::Print { value, .. } => {
                let v = self.emit_expr(value);
                self.line(&format!("KsPrint({});", v));
            }
            Statement::ExprStatement { expr, .. } => {
                let e = self.emit_expr(expr);
                self.line(&format!("{};", e));
            }
            Statement::Import { module, .. } => {
                self.line(&format!("// using {}; // KelpyShark import", module));
            }
            Statement::Throw { value, .. } => {
                let v = self.emit_expr(value);
                self.line(&format!("throw new Exception(KsStr({}));", v));
            }
            Statement::TryCatch { try_body, catch_var, catch_body, .. } => {
                self.line("try {");
                self.indent += 1;
                for s in try_body {
                    self.emit_statement(s);
                }
                self.indent -= 1;
                let exception_name = self.unique_temp("ksException");
                self.line(&format!("}} catch (Exception {}) {{", exception_name));
                self.indent += 1;
                let catch_local = self.unique_temp("ksCatch");
                self.line(&format!(
                    "object {} = (object)({}.Message ?? {}.ToString());",
                    catch_local, exception_name, exception_name
                ));
                self.variable_aliases.push((catch_var.clone(), catch_local));
                for s in catch_body {
                    self.emit_statement(s);
                }
                self.variable_aliases.pop();
                self.indent -= 1;
                self.line("}");
            }
            Statement::ClassDef { name, methods, .. } => {
                self.line(&format!("class {} {{", mangled_class_name(name)));
                self.indent += 1;
                for m in methods {
                    self.emit_statement(m);
                }
                self.indent -= 1;
                self.line("}");
            }
        }
    }

    // ── Expressions ───────────────────────────────────────────

    fn emit_expr(&self, expr: &Expr) -> String {
        match expr {
            Expr::NumberLiteral { value, .. } => {
                if *value == (*value as i64) as f64 {
                    format!("(double){}", *value as i64)
                } else {
                    format!("(double){}", value)
                }
            }
            Expr::StringLiteral { value, .. } => quote_cs_string(value),
            Expr::BooleanLiteral { value, .. } => {
                if *value { "true".to_string() } else { "false".to_string() }
            }
            Expr::NullLiteral { .. } => "null".to_string(),
            Expr::Identifier { name, .. } => self.variable(name),
            Expr::BinaryOp { left, op, right, .. } => {
                let l = self.emit_expr(left);
                let r = self.emit_expr(right);
                match op {
                    BinaryOperator::Add        => format!("KsAdd({}, {})", l, r),
                    BinaryOperator::Subtract   => format!("KsSub({}, {})", l, r),
                    BinaryOperator::Multiply   => format!("KsMul({}, {})", l, r),
                    BinaryOperator::Divide     => format!("KsDiv({}, {})", l, r),
                    BinaryOperator::Modulo     => format!("KsMod({}, {})", l, r),
                    BinaryOperator::Equal      => format!("KsEq({}, {})", l, r),
                    BinaryOperator::NotEqual   => format!("KsNeq({}, {})", l, r),
                    BinaryOperator::LessThan   => format!("KsLt({}, {})", l, r),
                    BinaryOperator::LessEqual  => format!("KsLe({}, {})", l, r),
                    BinaryOperator::GreaterThan => format!("KsGt({}, {})", l, r),
                    BinaryOperator::GreaterEqual => format!("KsGe({}, {})", l, r),
                    BinaryOperator::And => format!("(KsTruthy({}) && KsTruthy({}))", l, r),
                    BinaryOperator::Or  => format!("(KsTruthy({}) || KsTruthy({}))", l, r),
                }
            }
            Expr::UnaryOp { op, operand, .. } => {
                let o = self.emit_expr(operand);
                match op {
                    UnaryOperator::Negate => format!("(-(double)({}))", o),
                    UnaryOperator::Not    => format!("(!KsTruthy({}))", o),
                }
            }
            Expr::FunctionCall { callee, args, .. } => {
                let arg_strs: Vec<String> = args.iter().map(|a| self.emit_expr(a)).collect();
                match callee.as_ref() {
                    Expr::Identifier { name, .. } => {
                        if self.user_functions.contains(name) {
                            format!("Ks_{}({})", name, arg_strs.join(", "))
                        } else { match name.as_str() {
                            "len"   => format!("KsLen({})", arg_strs.join(", ")),
                            "type"  => format!("KsType({})", arg_strs.join(", ")),
                            "str"   => format!("KsStr({})", arg_strs.join(", ")),
                            "num"   => format!("KsNum({})", arg_strs.join(", ")),
                            "int"   => format!("KsInt({})", arg_strs.join(", ")),
                            "float" => format!("KsFloat({})", arg_strs.join(", ")),
                            "push"  => format!("KsPush({})", arg_strs.join(", ")),
                            "print" => format!("KsPrint({})", arg_strs.join(", ")),
                            "range" => format!("KsRange({})", arg_strs.join(", ")),
                            "input" => format!("KsInput({})", arg_strs.join(", ")),
                            "abs"   => format!("KsAbs({})", arg_strs.join(", ")),
                            "sqrt"  => format!("KsSqrt({})", arg_strs.join(", ")),
                            "floor" => format!("KsFloor({})", arg_strs.join(", ")),
                            "ceil"  => format!("KsCeil({})", arg_strs.join(", ")),
                            "round" => format!("KsRound({})", arg_strs.join(", ")),
                            "min"   => format!("KsMin({})", arg_strs.join(", ")),
                            "max"   => format!("KsMax({})", arg_strs.join(", ")),
                            "pow"   => format!("KsPow({})", arg_strs.join(", ")),
                            other   => format!("Ks_{}({})", other, arg_strs.join(", ")),
                        }}
                    }
                    other => {
                        let callee_str = self.emit_expr(other);
                        format!("{}({})", callee_str, arg_strs.join(", "))
                    }
                }
            }
            Expr::MethodCall { object, method, args, .. } => {
                let obj = self.emit_expr(object);
                let arg_strs: Vec<String> = args.iter().map(|a| self.emit_expr(a)).collect();
                // Emit as dynamic method call
                format!("((dynamic)({})).{}({})", obj, method, arg_strs.join(", "))
            }
            Expr::MemberAccess { object, member, .. } => {
                let obj = self.emit_expr(object);
                format!("KsMember({}, \"{}\")", obj, member)
            }
            Expr::Index { object, index, .. } => {
                let obj = self.emit_expr(object);
                let idx = self.emit_expr(index);
                format!("KsIndex({}, {})", obj, idx)
            }
            Expr::ListLiteral { elements, .. } => {
                let elems: Vec<String> = elements.iter().map(|e| self.emit_expr(e)).collect();
                format!("new List<object> {{ {} }}", elems.join(", "))
            }
            Expr::DictLiteral { entries, .. } => {
                let pairs = entries.iter().flat_map(|(key, value)| [self.emit_expr(key), self.emit_expr(value)]).collect::<Vec<_>>();
                format!("KsDict({})", pairs.join(", "))
            }
            Expr::StringInterpolation { parts, .. } => {
                // Use C# string interpolation via concatenation
                let mut pieces: Vec<String> = Vec::new();
                for part in parts {
                    match part {
                        StringPart::Literal(s) => {
                            pieces.push(quote_cs_string(s));
                        }
                        StringPart::Expression(expr) => {
                            pieces.push(format!("KsStr({})", self.emit_expr(expr)));
                        }
                    }
                }
                format!("({})", pieces.join(" + "))
            }
            Expr::New { class_name, args, .. } => {
                let arg_strs: Vec<String> = args.iter().map(|a| self.emit_expr(a)).collect();
                format!("new {}({})", mangled_class_name(class_name), arg_strs.join(", "))
            }
        }
    }
}

fn emit_variable_declarations(
    generator: &mut CsGenerator,
    statements: &[Statement],
    parameters: &HashSet<String>,
    globals: &HashSet<String>,
) {
    fn collect(statements: &[Statement], names: &mut HashSet<String>) {
        for statement in statements {
            match statement {
                Statement::Assignment { name, .. } => { names.insert(name.clone()); }
                Statement::If { then_body, else_body, .. } => {
                    collect(then_body, names);
                    if let Some(body) = else_body { collect(body, names); }
                }
                Statement::While { body, .. } => collect(body, names),
                Statement::For { variable, body, .. } => {
                    names.insert(variable.clone());
                    collect(body, names);
                }
                Statement::TryCatch { try_body, catch_var, catch_body, .. } => {
                    collect(try_body, names);
                    let mut catch_names = HashSet::new();
                    collect(catch_body, &mut catch_names);
                    catch_names.remove(catch_var);
                    names.extend(catch_names);
                }
                Statement::FunctionDef { .. } | Statement::ClassDef { .. } => {}
                _ => {}
            }
        }
    }

    let mut names = HashSet::new();
    collect(statements, &mut names);
    let mut names: Vec<_> = names.into_iter().filter(|name| !parameters.contains(name) && !globals.contains(name)).collect();
    names.sort();
    for name in names { generator.line(&format!("object {} = null;", variable_name(&name))); }
}

fn collect_global_variables(statements: &[Statement]) -> HashSet<String> {
    fn collect(statements: &[Statement], names: &mut HashSet<String>, shadowed: &mut Vec<String>) {
        for statement in statements {
            match statement {
                Statement::Assignment { name, .. } | Statement::CompoundAssignment { name, .. } => {
                    if !shadowed.iter().any(|item| item == name) { names.insert(name.clone()); }
                }
                Statement::If { then_body, else_body, .. } => {
                    collect(then_body, names, shadowed);
                    if let Some(body) = else_body { collect(body, names, shadowed); }
                }
                Statement::While { body, .. } => collect(body, names, shadowed),
                Statement::For { variable, body, .. } => {
                    if !shadowed.iter().any(|item| item == variable) { names.insert(variable.clone()); }
                    collect(body, names, shadowed);
                }
                Statement::TryCatch { try_body, catch_var, catch_body, .. } => {
                    collect(try_body, names, shadowed);
                    shadowed.push(catch_var.clone());
                    collect(catch_body, names, shadowed);
                    shadowed.pop();
                }
                Statement::FunctionDef { .. } | Statement::ClassDef { .. } => {}
                _ => {}
            }
        }
    }
    let mut names = HashSet::new();
    collect(statements, &mut names, &mut Vec::new());
    names
}

fn variable_name(name: &str) -> String { format!("ksv_{}", name) }
fn mangled_class_name(name: &str) -> String { format!("Ksc_{}", name) }

fn quote_cs_string(value: &str) -> String {
    let mut result = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => result.push_str("\\\""),
            '\\' => result.push_str("\\\\"),
            '\n' => result.push_str("\\n"),
            '\r' => result.push_str("\\r"),
            '\t' => result.push_str("\\t"),
            '\u{0008}' => result.push_str("\\b"),
            '\u{000c}' => result.push_str("\\f"),
            ch if ch.is_control() => result.push_str(&format!("\\u{:04x}", ch as u32)),
            ch => result.push(ch),
        }
    }
    result.push('"');
    result
}

fn sequence_terminates(statements: &[Statement]) -> bool {
    statements.last().is_some_and(statement_terminates)
}

fn statement_terminates(statement: &Statement) -> bool {
    match statement {
        Statement::Return { .. } | Statement::Throw { .. } => true,
        Statement::If { then_body, else_body: Some(else_body), .. } => {
            sequence_terminates(then_body) && sequence_terminates(else_body)
        }
        Statement::TryCatch { try_body, catch_body, .. } => {
            sequence_terminates(try_body) && sequence_terminates(catch_body)
        }
        _ => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lexer::Lexer;
    use crate::parser::Parser;

    fn gen_cs(source: &str) -> String {
        let mut lexer = Lexer::new(source);
        let tokens = lexer.tokenize().unwrap();
        let mut parser = Parser::new(tokens);
        let program = parser.parse().unwrap();
        generate(&program).unwrap()
    }

    #[test]
    fn test_cs_header() {
        let cs = gen_cs("print \"Hello\"");
        assert!(cs.contains("using System;"));
        assert!(cs.contains("class Program {"));
        assert!(cs.contains("static void Main(string[] args)"));
    }

    #[test]
    fn test_cs_print() {
        let cs = gen_cs(r#"print "Hello, World!""#);
        assert!(cs.contains("KsPrint(\"Hello, World!\")"));
    }

    #[test]
    fn test_cs_assignment() {
        let cs = gen_cs("x = 42");
        assert!(cs.contains("static object ksv_x = null;"));
        assert!(cs.contains("        ksv_x = (double)42;"));
    }

    #[test]
    fn cs_functions_update_globals_and_keep_local_variables_local() {
        let cs = gen_cs("count = 1\ndef advance():\n count = count + 1\n local = count\n return local\nend\nprint advance()\nprint count");
        assert!(cs.contains("static object ksv_count = null;"));
        assert!(cs.contains("ksv_count = KsAdd(ksv_count, (double)1);"));
        assert!(cs.contains("object ksv_local = null;"));
    }

    #[test]
    fn test_cs_function() {
        let cs = gen_cs("def greet(name) {\n  print name\n}");
        assert!(cs.contains("static object Ks_greet(object ksv_name)"));
        assert!(cs.contains("KsPrint(ksv_name)"));
    }

    #[test]
    fn test_cs_if_statement() {
        let cs = gen_cs("if x >= 5 {\n  print x\n}");
        assert!(cs.contains("if (KsTruthy(KsGe(ksv_x, (double)5)))"));
    }

    #[test]
    fn test_cs_while_loop() {
        let cs = gen_cs("while x < 10 {\n  x = x + 1\n}");
        assert!(cs.contains("while (KsTruthy(KsLt(ksv_x, (double)10)))"));
    }

    #[test]
    fn test_cs_for_loop() {
        let cs = gen_cs("for item in items {\n  print item\n}");
        assert!(cs.contains("foreach (object ksIterItem_0 in KsIter("));
        assert!(cs.contains("ksv_item = ksIterItem_0;"));
        assert!(cs.contains("return list.ToList();"));
        assert!(cs.contains("dict.Keys.OrderBy(KsStr, StringComparer.Ordinal).Cast<object>().ToList()"));
    }

    #[test]
    fn test_cs_list_literal() {
        let cs = gen_cs(r#"x = ["a", "b"]"#);
        assert!(cs.contains("new List<object>"));
    }

    #[test]
    fn test_cs_dict_literal() {
        let cs = gen_cs(r#"x = {"name": "Bob"}"#);
        assert!(cs.contains("new Dictionary<object,object>"));
        assert!(cs.contains("\"name\""));
    }

    #[test]
    fn test_cs_string_interpolation() {
        let cs = gen_cs(r#"
            name = "Bob"
            print "Hi {$name}"
        "#);
        assert!(cs.contains("KsStr(ksv_name)"));
    }

    #[test]
    fn test_cs_try_catch() {
        let cs = gen_cs("try {\n  print 1\n} catch (err) {\n  print err\n}");
        assert!(cs.contains("try {"));
        assert!(cs.contains("} catch (Exception ksException_0) {"));
    }

    #[test]
    fn test_cs_return() {
        let cs = gen_cs("def add(a, b) {\n  return a + b\n}");
        assert!(cs.contains("return KsAdd(ksv_a, ksv_b)"));
    }

    #[test]
    fn test_cs_runtime_helpers() {
        let cs = gen_cs("print 1");
        assert!(cs.contains("static object KsPrint("));
        assert!(cs.contains("static bool KsTruthy("));
        assert!(cs.contains("static object KsAdd("));
    }

    #[test]
    fn test_cs_boolean_ops() {
        let cs = gen_cs("x = true and false");
        assert!(cs.contains("KsTruthy(true) && KsTruthy(false)"));
    }

    #[test]
    fn checked_cs_rejects_unsupported_classes() {
        let mut lexer = Lexer::new("class Box:\nend");
        let program = Parser::new(lexer.tokenize().unwrap()).parse().unwrap();
        assert!(generate(&program).unwrap_err().contains("class definitions"));
        assert!(generate_checked(&program).unwrap_err().contains("class definitions"));
    }
}
